from __future__ import annotations

from django.db import models

from subscriptions.base_models import TimeStampedModel


class OnlineGatewayPaymentType(models.TextChoices):
    STANDARD = "STANDARD", "Standard One-Time Payment"
    AUTOPAY_MANDATE = "AUTOPAY_MANDATE", "UPI Autopay Mandate Registration"
    AUTOPAY_DEBIT = "AUTOPAY_DEBIT", "UPI Autopay Scheduled Recurring Debit"


class OnlineGatewayStatus(models.TextChoices):
    PENDING = "PENDING", "Pending / Initiated"
    SUCCESS = "SUCCESS", "Success / Paid"
    FAILED = "FAILED", "Failed"
    EXPIRED = "EXPIRED", "Expired"


class OnlineGatewayTransaction(TimeStampedModel):
    """
    Tracks online payment transactions and UPI Autopay lifecycle events.

    Acts as an idempotent buffer between external payment gateways (PhonePe)
    and the internal financial ledger. Only successful, cryptographically
    verified transactions trigger the atomic route_collection() posting engine.
    """

    merchant_transaction_id = models.CharField(
        max_length=64,
        unique=True,
        db_index=True,
        help_text="Unique transaction identifier generated by Subidha Core",
    )
    gateway_type = models.CharField(
        max_length=30,
        default="PHONEPE",
        help_text="Underlying payment provider (PHONEPE)",
    )
    payment_type = models.CharField(
        max_length=30,
        choices=OnlineGatewayPaymentType.choices,
        default=OnlineGatewayPaymentType.STANDARD,
        help_text="Transaction intent: one-time vs recurring UPI Autopay mandate/debit",
    )
    source_type = models.CharField(
        max_length=50,
        help_text="Source model type, e.g. EMI, SUBSCRIPTION, DIRECT_SALE",
    )
    source_id = models.PositiveIntegerField(
        null=True,
        blank=True,
        help_text="Primary key of the source entity",
    )
    customer = models.ForeignKey(
        "customers.Customer",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="gateway_transactions",
        help_text="Linked customer record",
    )
    amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        help_text="Transaction amount in INR",
    )
    status = models.CharField(
        max_length=20,
        choices=OnlineGatewayStatus.choices,
        default=OnlineGatewayStatus.PENDING,
        db_index=True,
    )
    provider_reference_id = models.CharField(
        max_length=120,
        blank=True,
        default="",
        help_text="Provider reference identifier (e.g. PhonePe transaction ID)",
    )
    mandate_id = models.CharField(
        max_length=120,
        blank=True,
        default="",
        help_text="Recurring UPI Autopay / e-NACH mandate identifier",
    )
    checkout_url = models.TextField(
        blank=True,
        default="",
        help_text="Payment link or UPI intent URI for redirection",
    )
    payload_snapshot = models.JSONField(
        default=dict,
        blank=True,
        help_text="Initial request payload sent to the gateway",
    )
    callback_snapshot = models.JSONField(
        default=dict,
        blank=True,
        help_text="Raw callback / webhook payload received from the gateway",
    )
    settled_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text="Timestamp when the collection was successfully posted to ledger",
    )
    settlement_error = models.TextField(
        blank=True,
        default="",
        help_text="Any error encountered during payment posting or ledger settlement",
    )
    settled_payment = models.ForeignKey(
        "payments.Payment",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="gateway_transaction_records",
        help_text="Internal Payment model row created upon settlement",
    )

    class Meta:
        db_table = "online_gateway_transactions"
        ordering = ["-created_at", "-id"]
        indexes = [
            models.Index(fields=["status", "created_at"], name="gw_tx_status_created_idx"),
            models.Index(fields=["source_type", "source_id"], name="gw_tx_source_idx"),
        ]

    def __str__(self):
        return f"{self.merchant_transaction_id} ({self.gateway_type} - {self.status} - ₹{self.amount})"
